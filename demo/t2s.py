for t, s in EXTRA.items():
    TABLE[ord(t)] = s


def to_simplified(text: str) -> str:
    return text.translate(TABLE)


def coverage(sample: str) -> dict:
    """粗估：样本里有多少字符被映射过。"""
    hit = sum(1 for ch in sample if ord(ch) in TABLE)
    total = sum(1 for ch in sample if "\u4e00" <= ch <= "\u9fff")
    return {"对子": len(TABLE) // 1, "样本汉字": total, "被映射": hit,
            "占比": f"{hit / max(total, 1):.1%}"}


